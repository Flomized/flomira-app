  t.after(env.cleanup);
  await env.ready();
  env.userScroll(1050);
  await env.load();
  const connector = env.video('conn-1.mp4'), next = env.video('two.mp4');
  connector.finish();
  env.playFor('two.mp4', 160);
  assert.equal(next.paused, false);
  env.container.querySelectorAll('.sw-route__dot')[2].emit('click', pointerClick);
  assert.equal(next.paused, true);
  assert.equal(env.smoothTarget, 3500);
